"""
src/sim/parse.py

EnergyPlus Simulation Output Parser for ClimateAdapt-Comfort.
Parses hourly eplusout.csv simulation outputs across building types:
- shelter_v1: single-zone passive shelter (20 m2)
- house: 3-zone detached house (60 m2)
- apartment: 2-zone mid-floor apartment (55 m2)
- commercial: 2-zone small commercial office (80 m2)

Extracts:
- Hourly indoor conditions: ta (Air Temp), tr (Mean Radiant Temp), rh (RH %)
  (for multi-zone buildings, computes building-wide average across thermal zones)
- Outdoor conditions: t_out (Outdoor Drybulb)
- Assumption variables: clo (Rule A-004), met (1.1 A-002), vel (0.15 m/s A-003)
- Commercial occupancy mask: Weekday 09:00-18:00 (Assumption A-011)
- Annual HVAC Energy Demand: O2 (kWh/m2)
"""

import os
import pandas as pd
import numpy as np

BUILDING_FLOOR_AREAS = {
    "shelter_v1": 20.0,
    "house": 60.0,
    "apartment": 55.0,
    "commercial": 80.0
}

def apply_clothing_rule_a004(t_outdoor):
    """
    Assumption A-004:
    clo = 0.5 if t_outdoor >= 25 C
    clo = 0.7 if 15 <= t_outdoor < 25 C
    clo = 1.0 if t_outdoor < 15 C
    """
    clo = np.full_like(t_outdoor, 0.7, dtype=float)
    clo[t_outdoor >= 25.0] = 0.5
    clo[t_outdoor < 15.0] = 1.0
    return clo

def compute_commercial_occupied_mask(n_hours=8760):
    """
    Assumption A-011:
    Commercial office occupancy is active on Weekdays (Mon-Fri) from 09:00 to 18:00.
    In TMYx / EnergyPlus, Jan 1 starts on Tuesday.
    Day of week for hour h: (h // 24 + 1) % 7 where 0=Mon, 1=Tue, ..., 4=Fri, 5=Sat, 6=Sun.
    """
    mask = np.zeros(n_hours, dtype=bool)
    for h in range(n_hours):
        day_idx = h // 24
        hour_of_day = (h % 24) + 1 # 1 to 24
        # Jan 1 is Tuesday (weekday index 1 in 0=Mon..6=Sun)
        weekday = (day_idx + 1) % 7
        if weekday < 5 and 9 <= hour_of_day <= 18:
            mask[h] = True
    return mask

def parse_simulation_csv(csv_path, floor_area_m2=None, building_type="shelter_v1"):
    """
    Parses eplusout.csv generated by EnergyPlus.
    Returns:
    - hourly_df: DataFrame with 8,760 hourly rows (or run period hours)
    - summary_dict: Dict with annual means and total ideal-loads energy (O2 in kWh/m2)
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Simulation output CSV not found: {csv_path}")
        
    if floor_area_m2 is None:
        floor_area_m2 = BUILDING_FLOOR_AREAS.get(building_type, 20.0)
        
    df = pd.read_csv(csv_path)
    df.columns = [c.strip() for c in df.columns]
    
    # Locate all columns matching output variables
    cols_ta = [c for c in df.columns if "Zone Mean Air Temperature" in c]
    cols_tr = [c for c in df.columns if "Zone Mean Radiant Temperature" in c]
    cols_rh = [c for c in df.columns if "Zone Air Relative Humidity" in c]
    col_tout = next((c for c in df.columns if "Site Outdoor Air Drybulb Temperature" in c), None)
    
    col_heat_list = [c for c in df.columns if "Zone Ideal Loads Zone Total Heating Rate" in c or "Zone Total Heating Energy" in c]
    col_cool_list = [c for c in df.columns if "Zone Ideal Loads Zone Total Cooling Rate" in c or "Zone Total Cooling Energy" in c]
    
    if not (cols_ta and cols_tr and cols_rh and col_tout):
        raise ValueError(f"Missing essential output variables in {csv_path}. Columns: {df.columns.tolist()}")
        
    hourly_df = pd.DataFrame()
    hourly_df['hour'] = range(len(df))
    
    # Average across conditioned zones
    hourly_df['ta'] = df[cols_ta].mean(axis=1).values
    hourly_df['tr'] = df[cols_tr].mean(axis=1).values
    hourly_df['rh'] = df[cols_rh].mean(axis=1).values
    hourly_df['t_out'] = df[col_tout].values
    
    # Assumptions A-002, A-003, A-004
    hourly_df['met'] = 1.1 # A-002 (residential default, commercial uses 1.1 - 1.2 seated)
    hourly_df['vel'] = 0.15 # A-003
    hourly_df['clo'] = apply_clothing_rule_a004(hourly_df['t_out'].values) # A-004
    
    # Occupancy mask
    if building_type == "commercial":
        hourly_df['occupied_mask'] = compute_commercial_occupied_mask(len(df))
    else:
        hourly_df['occupied_mask'] = np.ones(len(df), dtype=bool) # A-001 24h occupancy
        
    # Ideal Loads Energy (O2)
    # Sum heating and cooling watts across all zones
    if col_heat_list and col_cool_list:
        total_heat_watts = df[col_heat_list].sum(axis=1).values
        total_cool_watts = df[col_cool_list].sum(axis=1).values
        hourly_df['heating_watts'] = total_heat_watts
        hourly_df['cooling_watts'] = total_cool_watts
        total_heat_kwh = float(np.sum(total_heat_watts) / 1000.0)
        total_cool_kwh = float(np.sum(total_cool_watts) / 1000.0)
        total_energy_kwh = total_heat_kwh + total_cool_kwh
        o2_kwh_per_m2 = total_energy_kwh / floor_area_m2
    else:
        total_heat_kwh = 0.0
        total_cool_kwh = 0.0
        total_energy_kwh = 0.0
        o2_kwh_per_m2 = 0.0
        
    summary_dict = {
        "n_hours": len(hourly_df),
        "building_type": building_type,
        "floor_area_m2": floor_area_m2,
        "mean_ta": float(np.mean(hourly_df['ta'])),
        "mean_tr": float(np.mean(hourly_df['tr'])),
        "mean_rh": float(np.mean(hourly_df['rh'])),
        "mean_tout": float(np.mean(hourly_df['t_out'])),
        "max_ta": float(np.max(hourly_df['ta'])),
        "min_ta": float(np.min(hourly_df['ta'])),
        "total_heating_kwh": total_heat_kwh,
        "total_cooling_kwh": total_cool_kwh,
        "total_energy_kwh": total_energy_kwh,
        "o2_energy_kwh_per_m2": float(o2_kwh_per_m2)
    }
    
    return hourly_df, summary_dict

