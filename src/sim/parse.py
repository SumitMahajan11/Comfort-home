"""
EnergyPlus Simulation Output Parser for ClimateAdapt-Comfort.
Parses hourly eplusout.csv simulation outputs to extract:
- Hourly indoor conditions: ta (Air Temp), tr (Mean Radiant Temp), rh (RH %)
- Outdoor conditions: t_out (Outdoor Drybulb)
- Assumption variables: clo (Rule A-004), met (1.1 A-002), vel (0.15 m/s A-003)
- Annual HVAC Energy Demand: O2 (kWh/m2)
"""

import os
import pandas as pd
import numpy as np

def apply_clothing_rule_a004(t_outdoor):
    """
    Assumption A-004:
    clo = 0.5 if t_outdoor >= 25 C
    clo = 0.7 if 15 <= t_outdoor < 25 C
    clo = 1.0 if t_outdoor < 15 C
    """
    clo = np.full_like(t_outdoor, 0.7, dtype=float)
    clo[t_outdoor >= 25.0] = 0.5
    clo[t_outdoor < 15.0] = 1.0
    return clo

def parse_simulation_csv(csv_path, floor_area_m2=20.0):
    """
    Parses eplusout.csv generated by EnergyPlus.
    Returns:
    - hourly_df: DataFrame with 8,760 hourly rows (or run period hours)
    - summary_dict: Dict with annual means and total ideal-loads energy (O2 in kWh/m2)
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Simulation output CSV not found: {csv_path}")
        
    df = pd.read_csv(csv_path)
    
    # Strip whitespace from column names
    df.columns = [c.strip() for c in df.columns]
    
    # Locate column names matching output variables
    col_ta = next((c for c in df.columns if "Zone Mean Air Temperature" in c), None)
    col_tr = next((c for c in df.columns if "Zone Mean Radiant Temperature" in c), None)
    col_rh = next((c for c in df.columns if "Zone Air Relative Humidity" in c), None)
    col_tout = next((c for c in df.columns if "Site Outdoor Air Drybulb Temperature" in c), None)
    col_heat = next((c for c in df.columns if "Zone Ideal Loads Zone Total Heating Rate" in c or "Zone Total Heating Energy" in c), None)
    col_cool = next((c for c in df.columns if "Zone Ideal Loads Zone Total Cooling Rate" in c or "Zone Total Cooling Energy" in c), None)
    
    if not (col_ta and col_tr and col_rh and col_tout):
        raise ValueError(f"Missing essential output variables in {csv_path}. Columns: {df.columns.tolist()}")
        
    hourly_df = pd.DataFrame()
    hourly_df['hour'] = range(len(df))
    hourly_df['ta'] = df[col_ta].values
    hourly_df['tr'] = df[col_tr].values
    hourly_df['rh'] = df[col_rh].values
    hourly_df['t_out'] = df[col_tout].values
    
    # Assumptions A-002, A-003, A-004
    hourly_df['met'] = 1.1 # A-002
    hourly_df['vel'] = 0.15 # A-003
    hourly_df['clo'] = apply_clothing_rule_a004(hourly_df['t_out'].values) # A-004
    
    # Ideal Loads Energy (O2)
    # Heating and cooling rates are in Watts; 1 hour * Watts = Watt-hours = Wh / 1000 = kWh
    if col_heat and col_cool:
        hourly_df['heating_watts'] = df[col_heat].values
        hourly_df['cooling_watts'] = df[col_cool].values
        total_heat_kwh = np.sum(hourly_df['heating_watts']) / 1000.0
        total_cool_kwh = np.sum(hourly_df['cooling_watts']) / 1000.0
        total_energy_kwh = total_heat_kwh + total_cool_kwh
        o2_kwh_per_m2 = total_energy_kwh / floor_area_m2
    else:
        total_heat_kwh = 0.0
        total_cool_kwh = 0.0
        total_energy_kwh = 0.0
        o2_kwh_per_m2 = 0.0
        
    summary_dict = {
        "n_hours": len(hourly_df),
        "mean_ta": float(np.mean(hourly_df['ta'])),
        "mean_tr": float(np.mean(hourly_df['tr'])),
        "mean_rh": float(np.mean(hourly_df['rh'])),
        "mean_tout": float(np.mean(hourly_df['t_out'])),
        "max_ta": float(np.max(hourly_df['ta'])),
        "min_ta": float(np.min(hourly_df['ta'])),
        "total_heating_kwh": float(total_heat_kwh),
        "total_cooling_kwh": float(total_cool_kwh),
        "total_energy_kwh": float(total_energy_kwh),
        "o2_energy_kwh_per_m2": float(o2_kwh_per_m2)
    }
    
    return hourly_df, summary_dict

